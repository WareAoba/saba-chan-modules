def _unescape_property(value):
    """Java .properties 값의 이스케이프를 푼다 (\\uXXXX, \\:, \\= 등).
    줄바꿈 \\n·\\r은 이스케이프 모양 그대로 둔다: 한 줄 값만 저장할 수 있어 진짜 줄바꿈으로 풀면 다시 저장하지 못한다"""
    def repl(m):
        s = m.group(1)
        if len(s) == 11:  # 서러게이트 쌍(BMP 밖 글자)은 한 글자로 합친다
            return chr(0x10000 + ((int(s[1:5], 16) - 0xD800) << 10) + int(s[7:], 16) - 0xDC00)
        if len(s) == 5:
            return chr(int(s[1:], 16))
        if s in "nr":
            return "\\" + s
        return {"t": "\t", "f": "\f"}.get(s, s)
    return re.sub(r"\\(u[dD][89abAB][0-9a-fA-F]{2}\\u[dD][c-fC-F][0-9a-fA-F]{2}|u[0-9a-fA-F]{4}|.)", repl, value)


def _default_properties(config=None):
    """새 server.properties의 값: module.toml 설정 기본값(공용 setting_defaults_to_file) 위에 사바쨩이 정하는
    원격 접속 값(module.toml [remote_access]). 기본값을 module.toml 한 곳에만 둔다. 동봉 server.properties는
    1.21.9 서버가 만든 키 목록의 기준 파일일 뿐이다 (test_module_toml)"""
    return {**setting_defaults_to_file(MODULE_DIR), **remote_access_values(MODULE_DIR, config)}


def _utf16_escapes(m):
    """글자 하나를 `\\uXXXX`로 (BMP 밖은 서러게이트 쌍 두 개)"""
    units = m.group(0).encode("utf-16-be", "surrogatepass").hex().upper()
    return "".join("\\u" + units[i:i + 4] for i in range(0, len(units), 4))


def _escape_property(value):
    """Java Properties.store(Writer)처럼 값을 쓴다: `\\`·`=`·`:`·`#`·`!` 앞에 `\\`, 맨 앞 공백도 이스케이프.
    서버가 쓰는 파일과 같은 모양(level-type=minecraft\\:normal)이 된다. 줄바꿈 이스케이프 \\n·\\r은 그대로 둔다
    (_unescape_property가 풀지 않은 모양). 진짜 줄바꿈은 공용 도우미가 거부한다.
    ASCII가 아닌 글자는 Properties.store(OutputStream)처럼 `\\uXXXX`로 쓴다: 1.20 전 서버는 이 파일을 ISO 8859-1로 읽는다"""
    value = str(value)
    out = re.sub(r"\\(?![nr])|[=:#!]", lambda m: "\\" + m.group(0), value)
    out = re.sub(r"[^\x00-\x7e]", _utf16_escapes, out)
    return "\\" + out if out.startswith(" ") else out


class ServerPropertiesManager:
    """Read/write Minecraft server.properties files. 값은 Java Properties 이스케이프로 읽고 쓴다"""

    def __init__(self, working_dir):
        self.path = os.path.join(working_dir, "server.properties")

    def exists(self):
        return os.path.isfile(self.path)

    def read(self):
        """Parse server.properties into a dict. 인코딩 추측(UTF-8 → cp949 → 로캘)은 공용 read_key_values가 한다"""
        if not self.exists():
            return {}
        try:
            return {k: _unescape_property(v) for k, v in read_key_values(self.path, strip_values=True).items()}
        except OSError:
            return {}

    def write(self, properties):
        """Write a full properties dict (replaces entire file)."""
        header = (
            "#Minecraft server properties\n"
            f"#Generated by saba-chan on {time.strftime('%c')}\n"
        )
        body = "".join(f"{key}={_escape_property(value)}\n" for key, value in sorted(properties.items()))
        try:
            atomic_write(self.path, (header + body).encode("utf-8"))
            return True
        except OSError:
            return False

    def update(self, changes):
        """Merge changes into existing properties (preserves comments). 바꾼 값은 ASCII라 남은 줄의 인코딩(UTF-8)만 지킨다"""
        if not self.exists():
            return self.write({**_default_properties(), **changes})
        try:
            update_key_values(self.path, {k: _escape_property(v) for k, v in changes.items()}, write_encoding="utf-8")
            return True
        except OSError:
            return False
